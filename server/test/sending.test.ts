test('a lost send result is retried with the same key only when the provider is idempotent', async (t) => {
  const { install, owner, nl, ctx, accountId } = await sendableInstall()
  t.after(() => { install.close(); sendHooks.provider = null })
  addContacts(ctx, nl.id, 3)
  const idempotent = fakeProvider({ idempotency: true, plan: (call) => (call === 1 ? 'throw' : null) })
  const first = await createIssue(owner, nl.id)
  await owner.action('campaigns.send', { campaignId: first.id })
  await install.runJobs()
  assert.equal(ctx.db.get<{ n: number }>("SELECT COUNT(*) AS n FROM deliveries WHERE campaign_id = ? AND status = 'queued'", first.id)!.n, 1, 'the lost delivery is queued again')
  install.clock.advance(90_000)
  const done = await drive(install, owner, first.id)
  assert.equal(done.status, 'sent')
  assert.equal(idempotent.keys.length, 4)
  assert.equal(idempotent.keys[0], idempotent.keys[3], 'the retry reuses the idempotency key')
  assert.equal(install.outbox(accountId).filter((r) => r.kind === 'campaign').length, 3)
  idempotent.reset()

  const plain = fakeProvider({ idempotency: false, plan: (call) => (call === 1 ? 'throw' : null) })
  const second = await createIssue(owner, nl.id)
  install.clock.advance(2000)
  await owner.action('campaigns.send', { campaignId: second.id })
  const finished = await drive(install, owner, second.id)
  assert.equal(finished.status, 'sent')
  assert.equal(plain.keys.length, 3, 'nothing is resent without idempotency')
  const progress = await owner.action('campaigns.progress', { campaignId: second.id })
  assert.equal(progress.counts.unknown, 1)
  assert.equal(progress.counts.sent, 2)
  assert.equal(install.outbox(accountId).filter((r) => r.kind === 'campaign').length, 5)
  plain.reset()
})

