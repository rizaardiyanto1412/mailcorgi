test('an uncertain reminder delivery never causes another automatic reminder', async (t) => {
  const { install, owner, nl, ctx } = await sendableInstall()
  t.after(() => { sendHooks.provider = null; install.close() })
  const [id] = addContacts(ctx, nl.id, 1)
  ctx.db.run('UPDATE contacts SET ignored_streak = 8, subscribed_at = ? WHERE id = ?', ctx.now() - 91 * DAY, id)
  let calls = 0
  sendHooks.provider = (store) => ({
    ...testProvider(store), capabilities: { identities: false, events: false, idempotency: false },
    async send() { calls++; return { ok: false, kind: 'unknown', message: 'Provider response lost' } },
  })
  const settings = await owner.action('hygiene.settings', { newsletterId: nl.id })
  await owner.action('hygiene.updateSettings', { newsletterId: nl.id, ...settings })
  await install.runJobs()
  install.clock.advance(1000)
  await install.runJobs()
  await owner.action('hygiene.updateSettings', { newsletterId: nl.id, ...settings })
  await install.runJobs()
  assert.equal(calls, 1)
  assert.equal((await owner.action('contacts.get', { newsletterId: nl.id, contactId: id })).contact.status, 'subscribed')
  assert.equal((await owner.action('hygiene.health', { newsletterId: nl.id })).awaitingReply, 0)
})
