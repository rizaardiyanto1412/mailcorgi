/** A provider wrapper around the test provider that records calls and can fail on demand. */
function fakeProvider(opts: { idempotency?: boolean; plan?: (call: number, key: string) => SendResult | 'throw' | null } = {}) {
  const keys: string[] = []
  sendHooks.provider = (ctx) => {
    const base = testProvider(ctx)
    const provider: EmailProvider = {
      name: 'test', capabilities: { identities: false, events: false, idempotency: opts.idempotency ?? true },
      async send(msg) {
        keys.push(msg.idempotencyKey)
        const planned = opts.plan?.(keys.length, msg.idempotencyKey) ?? null
        if (planned === 'throw') throw new Error('connection lost')
        if (planned) return planned
        return base.send(msg)
      },
    }
    return provider
  }
  return { keys, reset: () => { sendHooks.provider = null } }
}

