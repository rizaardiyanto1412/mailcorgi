const headers = (key: string) => ({ authorization: `Bearer ${key}`, 'content-type': 'application/json', accept: 'application/json, text/event-stream' })
const rpc = (method: string, params?: unknown, id: string | number = 1) => JSON.stringify({ jsonrpc: '2.0', id, method, params })

for (const cloud of [false, true]) test(`API keys, REST and MCP work in ${cloud ? 'cloud' : 'self-hosted'} mode`, async (t) => {
  const install = await createInstall({ cloud })
  t.after(() => install.close())
  const owner = await install.signUp({ email: 'owner@example.com' })
  const key = await owner.action('apikeys.create', { name: 'Automation', access: 'full' })
  assert.match(key.secret, new RegExp(`^mc_${owner.accountId}_`))
  const list = await owner.action('apikeys.list', {})
  assert.equal(list.keys[0].lastUsedAt, null)
  assert.equal(JSON.stringify(list).includes(key.secret), false)
  assert.equal(JSON.stringify(list).includes('hash'), false)
  const request = (path: string, init: RequestInit = {}) => install.fetch(path, { ...init, headers: { ...headers(key.secret), ...init.headers } })
  const created = await request('/api/v1/newsletters', { method: 'POST', body: JSON.stringify({ name: 'Weekly' }) })
  assert.equal(created.status, 200)
  const newsletter = await created.json()
  assert.equal((await (await request(`/api/v1/newsletters/${newsletter.id}`)).json()).name, 'Weekly')
  assert.equal((await (await request('/api/v1/newsletters?includeArchived=false')).json()).newsletters.length, 1)
  const invalid = await request('/api/v1/newsletters?includeArchived=wrong')
  assert.equal(invalid.status, 400)
  assert.equal((await invalid.json()).error.code, 'invalid_input')
  const renamed = await request(`/api/v1/newsletters/${newsletter.id}`, { method: 'PATCH', body: JSON.stringify({ newsletterId: 'wrong', name: 'Renamed' }) })
  assert.equal((await renamed.json()).name, 'Renamed')
  const handshake = await request('/mcp', { method: 'POST', body: rpc('initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'Test', version: '1' } }) })
  const hello = await handshake.json()
  assert.equal(hello.result.protocolVersion, '2025-06-18')
  assert.ok(hello.result.capabilities.tools)
  const called = await (await request('/mcp', { method: 'POST', body: rpc('tools/call', { name: 'newsletters_list', arguments: {} }) })).json()
  assert.equal(called.result.isError, false)
  assert.equal(called.result.structuredContent.newsletters[0].name, 'Renamed')
  assert.deepEqual(JSON.parse(called.result.content[0].text), called.result.structuredContent)
  const usedAt = (await owner.action('apikeys.list', {})).keys[0].lastUsedAt
  install.clock.advance(59_999)
  await request('/api/v1/newsletters')
  assert.equal((await owner.action('apikeys.list', {})).keys[0].lastUsedAt, usedAt)
  install.clock.advance(1)
  await request('/api/v1/newsletters')
  assert.equal((await owner.action('apikeys.list', {})).keys[0].lastUsedAt, install.clock.now())
  await owner.action('apikeys.rename', { keyId: key.id, name: 'Renamed key' })
  assert.equal((await owner.action('apikeys.list', {})).keys[0].name, 'Renamed key')
  await owner.action('apikeys.revoke', { keyId: key.id })
  assert.equal((await request('/api/v1/newsletters')).status, 401)
  assert.equal((await request('/mcp', { method: 'POST', body: rpc('ping') })).status, 401)
  const wrong = await install.fetch('/api/v1/newsletters', { headers: headers(`mc_${owner.accountId}_${'x'.repeat(43)}`) })
  assert.equal(wrong.status, 401)
  assert.equal((await wrong.json()).error.code, 'unauthorized')
  const missing = await install.fetch('/api/v1/newsletters')
  assert.equal(missing.status, 401)
  assert.equal((await missing.json()).error.code, 'unauthorized')
})

test('keys are owner-only, account isolated, paginated, and never disclose a secret again', async (t) => {
  const install = await createInstall({ cloud: true })
  t.after(() => install.close())
  const a = await install.signUp({ email: 'a@example.com' })
  const b = await install.signUp({ email: 'b@example.com' })
  const key = await a.action('apikeys.create', { name: 'First', access: 'read' })
  const other = await a.action('apikeys.create', { name: 'Second', access: 'full' })
  const page = await a.action('apikeys.list', { limit: 1 })
  assert.equal(page.keys.length, 1)
  assert.ok(page.nextCursor)
  const next = await a.action('apikeys.list', { limit: 1, cursor: page.nextCursor })
  assert.equal(next.keys.length, 1)
  assert.notEqual(page.keys[0].id, next.keys[0].id)
  assert.equal(next.nextCursor, null)
  assert.equal((await expectError(() => b.action('apikeys.rename', { keyId: key.id, name: 'Stolen' }))).status, 404)
  assert.equal((await b.action('apikeys.list', {})).keys.length, 0)
  const forged = `mc_${b.accountId}_${key.secret.split('_').slice(3).join('_')}`
  assert.equal((await install.fetch('/api/v1/newsletters', { headers: headers(forged) })).status, 401)
  const ctx = install.app.account(a.accountId!).ctx
  const member: Actor = { userId: 'member', email: 'member@example.com', owner: false, grants: { newsletter: 'admin' }, access: 'full', via: 'web', installAdmin: false }
  for (const [name, input] of [['apikeys.create', { name: 'No', access: 'full' }], ['apikeys.list', {}], ['apikeys.rename', { keyId: key.id, name: 'No' }], ['apikeys.revoke', { keyId: other.id }]] as const) {
    await assert.rejects(runAction(ctx, name, input, member), (err: unknown) => err instanceof AppError && err.status === 403)
  }
})

test('live registry additions appear in REST, OpenAPI, MCP and docs; read keys cannot write or send', async (t) => {
  const install = await createInstall()
  t.after(() => install.close())
  const owner = await install.signUp({ email: 'owner@example.com' })
  const key = await owner.action('apikeys.create', { name: 'Read', access: 'read' })
  const full = await owner.action('apikeys.create', { name: 'Full', access: 'full' })
  const fake = defineAction({ name: 'fake.read', description: 'Runtime action', scope: 'account', role: 'member', effect: 'read', input: z.object({ id: z.string().describe('Resource id'), limit: z.number().int().default(10).describe('Maximum rows'), flags: z.array(z.boolean()).optional().describe('Flags') }), rest: { method: 'GET', path: '/runtime/:id' }, mcp: { title: 'Runtime read', destructive: false }, handler: (_ctx, input) => input })
  const writes = (['write', 'send'] as const).map((effect) => defineAction({ name: `fake.${effect}`, description: `Runtime ${effect}`, scope: 'account', role: 'member', effect, input: z.object({}), rest: { method: 'POST', path: `/runtime/${effect}` }, mcp: { title: effect, destructive: false }, handler: () => ({ changed: true }) }))
  accountRegistry.actions.set(fake.name, fake)
  for (const action of writes) accountRegistry.actions.set(action.name, action)
  t.after(() => { for (const action of [fake, ...writes]) accountRegistry.actions.delete(action.name) })
  const rest = await install.fetch('/api/v1/runtime/abc?limit=2&flags=%5Btrue%2Cfalse%5D', { headers: headers(key.secret) })
  assert.deepEqual(await rest.json(), { id: 'abc', limit: 2, flags: [true, false] })
  const api = await (await install.fetch('/api/v1/openapi.json', { headers: headers(key.secret) })).json()
  assert.equal(api.openapi, '3.1.0')
  const toolsResponse = await (await install.fetch('/mcp', { method: 'POST', headers: headers(key.secret), body: rpc('tools/list') })).json()
  const tools: { name: string; annotations: { readOnlyHint: boolean; destructiveHint: boolean } }[] = toolsResponse.result.tools
  assert.equal(new Set(tools.map((tool) => tool.name)).size, tools.length)
  for (const action of [...accountRegistry.actions.values(), ...controlRegistry.actions.values()]) {
    if (action.rest) assert.equal(api.paths[`/api/v1${action.rest.path.replace(/:([^/]+)/g, '{$1}')}`][action.rest.method.toLowerCase()].operationId, action.name)
    if (action.mcp) assert.ok(tools.some((tool) => tool.name === action.name.replace(/\./g, '_')))
  }
  assert.ok((await owner.action('api.reference', {})).endpoints.some((endpoint) => endpoint.name === fake.name))
  assert.match(await (await install.fetch('/llms.txt')).text(), /GET \/api\/v1\/runtime\/:id/)
  for (const action of writes) {
    assert.equal((await install.fetch(`/api/v1${action.rest!.path}`, { method: 'POST', headers: headers(key.secret), body: '{}' })).status, 403)
    const call = await (await install.fetch('/mcp', { method: 'POST', headers: headers(key.secret), body: rpc('tools/call', { name: action.name.replace('.', '_'), arguments: {} }) })).json()
    assert.equal(call.result.isError, true)
    assert.equal(call.result.structuredContent.error.code, 'forbidden')
    assert.equal(tools.find((tool) => tool.name === action.name.replace('.', '_'))?.annotations.readOnlyHint, false)
    assert.equal((await install.fetch(`/api/v1${action.rest!.path}`, { method: 'POST', headers: headers(full.secret), body: '{}' })).status, 200)
  }
  assert.equal(tools.find((tool) => tool.name === 'fake_send')?.annotations.destructiveHint, true)
  assert.ok(tools.some((tool) => tool.name === 'install_settings_set'))
  const controlAction = defineAction({ name: 'fake.control', description: 'Read from the control store', scope: 'control', role: 'user', effect: 'read', input: z.object({}), rest: { method: 'GET', path: '/control-test' }, mcp: { title: 'Control test', destructive: false }, handler: (ctx) => ({ store: ctx.kind }) })
  const adminAction = defineAction({ ...controlAction, name: 'fake.admin', role: 'installAdmin', rest: { method: 'GET', path: '/admin-test' } })
  controlRegistry.actions.set(controlAction.name, controlAction)
  controlRegistry.actions.set(adminAction.name, adminAction)
  t.after(() => { controlRegistry.actions.delete(controlAction.name); controlRegistry.actions.delete(adminAction.name) })
  assert.deepEqual(await (await install.fetch('/api/v1/control-test', { headers: headers(full.secret) })).json(), { store: 'control' })
  assert.equal((await install.fetch('/api/v1/admin-test', { headers: headers(full.secret) })).status, 403)
  const controlCall = await (await install.fetch('/mcp', { method: 'POST', headers: headers(full.secret), body: rpc('tools/call', { name: 'fake_admin' }) })).json()
  assert.equal(controlCall.result.structuredContent.error.code, 'forbidden')
})

test('key rate limits are shared across REST and MCP, separate per key, and reset each minute', async (t) => {
  const install = await createInstall()
  t.after(() => install.close())
  const owner = await install.signUp({ email: 'owner@example.com' })
  const key = await owner.action('apikeys.create', { name: 'Limited', access: 'read' })
  const other = await owner.action('apikeys.create', { name: 'Other', access: 'read' })
  for (let i = 0; i < 600; i++) assert.equal((await install.fetch('/api/v1/newsletters', { headers: headers(key.secret) })).status, 200)
  const limited = await install.fetch('/mcp', { method: 'POST', headers: headers(key.secret), body: rpc('ping') })
  assert.equal(limited.status, 429)
  assert.equal(limited.headers.get('Retry-After'), '60')
  assert.equal((await limited.json()).error.code, 'rate_limited')
  assert.equal((await install.fetch('/api/v1/newsletters', { headers: headers(other.secret) })).status, 200)
  install.clock.advance(60_000)
  assert.equal((await install.fetch('/api/v1/newsletters', { headers: headers(key.secret) })).status, 200)
})

test('MCP protocol errors, notifications, origin checks and tool errors have distinct behavior', async (t) => {
  const install = await createInstall()
  t.after(() => install.close())
  const owner = await install.signUp({ email: 'owner@example.com' })
  const key = await owner.action('apikeys.create', { name: 'MCP', access: 'full' })
  const post = (body: string, extra: Record<string, string> = {}) => install.fetch('/mcp', { method: 'POST', headers: { ...headers(key.secret), ...extra }, body })
  assert.equal((await install.fetch('/mcp', { headers: headers(key.secret) })).status, 405)
  assert.equal((await post(rpc('ping'), { origin: 'https://evil.example.com' })).status, 403)
  assert.equal((await post(rpc('ping'), { 'content-type': 'text/plain' })).status, 415)
  assert.equal((await post(rpc('ping'), { accept: 'text/html' })).status, 406)
  assert.equal((await post(rpc('ping'), { 'mcp-protocol-version': 'unsupported' })).status, 400)
  assert.equal((await (await post('{')).json()).error.code, -32700)
  assert.equal((await (await post('[]')).json()).error.code, -32600)
  assert.equal((await (await post(rpc('missing'))).json()).error.code, -32601)
  assert.equal((await (await post(rpc('initialize', {}))).json()).error.code, -32602)
  assert.equal((await (await post(rpc('tools/call', {}))).json()).error.code, -32602)
  assert.equal((await post(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }))).status, 202)
  assert.deepEqual((await (await post(rpc('ping', undefined, 'ping-id'))).json()).result, {})
  for (const [name, args] of [['unknown', {}], ['newsletters_get', { newsletterId: 'missing' }], ['newsletters_create', {}]]) {
    const result = (await (await post(rpc('tools/call', { name, arguments: args }))).json()).result
    assert.equal(result.isError, true)
    assert.ok(result.structuredContent.error.code)
  }
})

test('idempotency survives restarts, rejects changed input and concurrent calls, expires in 24 hours', async (t) => {
  let install = await createInstall()
  t.after(() => install.close())
  const owner = await install.signUp({ email: 'owner@example.com' })
  const key = await owner.action('apikeys.create', { name: 'Writer', access: 'full' })
  const write = (body: unknown, token = 'once') => install.fetch('/api/v1/newsletters', { method: 'POST', headers: { ...headers(key.secret), 'Idempotency-Key': token }, body: JSON.stringify(body) })
  const first = await write({ name: 'Unique' })
  const firstValue = await first.json()
  assert.equal(first.status, 200)
  const [second, third] = await Promise.all([write({ name: 'Unique' }), write({ name: 'Unique' })])
  assert.deepEqual(await second.json(), firstValue)
  assert.deepEqual(await third.json(), firstValue)
  assert.equal(second.headers.get('Idempotency-Replayed'), 'true')
  assert.equal((await write({ name: 'Different' })).status, 409)
  install = await install.restart()
  assert.deepEqual(await (await write({ name: 'Unique' })).json(), firstValue)
  assert.equal((await install.app.account(owner.accountId!).ctx.db.get<{ n: number }>('SELECT count(*) AS n FROM newsletters'))?.n, 1)
  install.clock.advance(86_400_000)
  assert.equal((await write({ name: 'After expiry' })).status, 200)
  let release: () => void = () => {}
  const gate = new Promise<void>((resolve) => { release = resolve })
  let started: () => void = () => {}
  const entered = new Promise<void>((resolve) => { started = resolve })
  let count = 0
  const action = defineAction({ name: 'fake.slow', description: 'Slow send', scope: 'account', role: 'owner', effect: 'send', input: z.object({}), rest: { method: 'POST', path: '/slow' }, handler: async () => { count++; started(); await gate; return { sent: true } } })
  accountRegistry.actions.set(action.name, action)
  t.after(() => accountRegistry.actions.delete(action.name))
  const slow = () => install.fetch('/api/v1/slow', { method: 'POST', headers: { ...headers(key.secret), 'Idempotency-Key': 'slow' }, body: '{}' })
  const pending = slow()
  await entered
  assert.equal((await slow()).status, 409)
  release()
  assert.equal((await pending).status, 200)
  assert.equal((await slow()).status, 200)
  assert.equal(count, 1)
  const crash = defineAction({ ...action, name: 'fake.crash', rest: { method: 'POST', path: '/crash' }, handler: () => { count++; throw new Error('Outcome uncertain') } })
  accountRegistry.actions.set(crash.name, crash)
  t.after(() => accountRegistry.actions.delete(crash.name))
  const fail = () => install.fetch('/api/v1/crash', { method: 'POST', headers: { ...headers(key.secret), 'Idempotency-Key': 'crash' }, body: '{}' })
  assert.equal((await fail()).status, 500)
  assert.equal((await fail()).status, 409)
  assert.equal(count, 2)
})
