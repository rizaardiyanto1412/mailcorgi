test('hard-bounce protection uses exactly the trailing 1,000 and triggers only above 5%', async (t) => {
  const { install, owner, nl, ctx, accountId } = await sendableInstall()
  t.after(() => install.close())
  addContacts(ctx, nl.id, 1001)
  const issue = await createIssue(owner, nl.id)
  await owner.action('campaigns.send', { campaignId: issue.id })
  await drive(install, owner, issue.id)
  const rows = ctx.db.all<{ id: number; email: string }>('SELECT id, email FROM deliveries WHERE campaign_id = ? ORDER BY id LIMIT 52', issue.id)
  const events = rows.map((d, i) => ({ id: `hard-${i}`, type: 'bounce' as const, bounce: { permanent: true, nonexistent: false, reason: 'Mailbox refused' }, accountId, deliveryId: String(d.id), messageId: `hard-m-${i}`, recipient: d.email, occurredAt: ctx.now() }))
  await install.app.stores.account(accountId).ingestProviderEvents({ events: events.slice(0, 51) })
  const exact = await owner.action('hygiene.health', { newsletterId: nl.id })
  assert.equal(exact.rates.total, 1000)
  assert.equal(exact.rates.bounces, 50, 'the oldest delivery is outside the window')
  assert.equal(exact.protection, null)
  await install.app.stores.account(accountId).ingestProviderEvents({ events: [events[51]] })
  assert.equal((await owner.action('hygiene.health', { newsletterId: nl.id })).protection?.reason, 'bounce_rate')
})

