test('provider refusals map to failed, retried and throttled deliveries', async (t) => {
  const { install, owner, nl, ctx } = await sendableInstall()
  t.after(() => { install.close(); sendHooks.provider = null })
  addContacts(ctx, nl.id, 3)
  const issue = await createIssue(owner, nl.id)
  const seen = new Map<string, number>()
  const plan = fakeProvider({ plan: (_call, key) => {
    const n = (seen.get(key) ?? 0) + 1
    seen.set(key, n)
    if (key.endsWith(':1')) return { ok: false, kind: 'permanent', message: 'Address rejected' }
    if (key.endsWith(':2') && n <= 2) return { ok: false, kind: 'temporary', message: 'Try later' }
    if (key.endsWith(':3') && n === 1) return { ok: false, kind: 'throttled', message: 'Slow down', retryAfterMs: 5000 }
    return null
  } })
  await owner.action('campaigns.send', { campaignId: issue.id })
  await install.runJobs()
  const rows = () => ctx.db.all<{ id: number; status: string; attempts: number; error: string | null }>('SELECT id, status, attempts, error FROM deliveries WHERE campaign_id = ? ORDER BY id', issue.id)
  assert.deepEqual(rows().map((r) => r.status), ['failed', 'queued', 'queued'])
  assert.equal(rows()[0].error, 'Address rejected')
  const next = install.app.account(owner.accountId!).nextWakeAt()!
  assert.ok(next >= install.clock.now() + 4000, 'throttling backs off for about retryAfterMs')
  const done = await drive(install, owner, issue.id, { stepMs: 30_000, maxSeconds: 60 })
  assert.equal(done.status, 'sent')
  assert.deepEqual(rows().map((r) => r.status), ['failed', 'sent', 'sent'])
  assert.equal(rows()[1].attempts, 3)
  assert.ok(plan.keys.length >= 6)
  plan.reset()
})

test('gradual sending warms up never-emailed contacts in released steps', async (t) => {
  const { install, owner, nl, ctx, accountId } = await sendableInstall()
  t.after(() => install.close())
  const fresh = addContacts(ctx, nl.id, 200)
  const known = addContacts(ctx, nl.id, 10, 'known')
  ctx.db.run(`UPDATE contacts SET sent_count = 2 WHERE id IN (${known.map(() => '?').join(',')})`, ...known)
  const issue = await createIssue(owner, nl.id)
  const count = await owner.action('campaigns.audienceCount', { campaignId: issue.id })
  assert.deepEqual(count, { total: 210, fresh: 200, engaged: 0 })
  await owner.action('campaigns.send', { campaignId: issue.id, gradual: true })
  const started = install.clock.now()
  let progress = await owner.action('campaigns.progress', { campaignId: issue.id })
  assert.deepEqual(progress.steps.map((s) => [s.kind, s.planned, s.state]), [['warmup', 14, 'released'], ['warmup', 10, 'pending'], ['main', 186, 'pending']])
  assert.equal(progress.steps[1].releaseAt, started + 30 * 60_000)
  await install.runJobs()
  progress = await owner.action('campaigns.progress', { campaignId: issue.id })
  assert.equal(progress.counts.sent, 14)
  assert.equal(progress.counts.queued, 196)
  assert.equal(install.app.account(accountId).nextWakeAt(), started + 30 * 60_000, 'the job sleeps until the next step')
  install.clock.advance(30 * 60_000)
  await install.runJobs()
  progress = await owner.action('campaigns.progress', { campaignId: issue.id })
  assert.equal(progress.counts.sent, 24)
  assert.deepEqual(progress.steps.map((s) => s.state), ['done', 'done', 'pending'])
  await owner.action('campaigns.sendMore', { campaignId: issue.id })
  await install.runJobs()
  progress = await owner.action('campaigns.progress', { campaignId: issue.id })
  assert.equal(progress.counts.sent, 210)
  assert.equal(progress.status, 'sent')
  assert.equal((await expectError(() => owner.action('campaigns.sendMore', { campaignId: issue.id }))).code, 'invalid_transition')
  assert.ok(known.every((id) => ctx.db.get<{ send_id: string }>('SELECT send_id FROM deliveries WHERE contact_id = ?', id)!.send_id === progress.steps[0].id), 'known contacts go in the first step')
  assert.ok(fresh.length)
})

