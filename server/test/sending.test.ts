test('a blocked or limited cloud account cannot send, and a block mid-send pauses it', async (t) => {
  const { install, owner, nl, ctx, accountId } = await sendableInstall({ cloud: true, env: { SEND_BATCH_SIZE: '5' } })
  t.after(() => install.close())
  addContacts(ctx, nl.id, 12)
  const stores = install.app.stores.account(accountId)
  const policy = (version: number, status: 'active' | 'blocked', maxEmailsPerMonth: number | null) => ({ version, status, plan: 'free', limits: { maxContacts: null, maxEmailsPerMonth, maxNewsletters: null, maxTeamPerNewsletter: null } })
  await stores.applyPolicy(policy(1001, 'active', 10))
  const issue = await createIssue(owner, nl.id)
  const limited = await expectError(() => owner.action('campaigns.send', { campaignId: issue.id }))
  assert.equal(limited.code, 'limit_reached')
  assert.deepEqual(limited.details, { billingUrl: '/settings/billing' })
  await stores.applyPolicy(policy(1002, 'active', null))
  await owner.action('campaigns.send', { campaignId: issue.id })
  await install.app.tick()
  await stores.applyPolicy(policy(1003, 'blocked', null))
  await install.app.tick()
  const c = await owner.action('campaigns.get', { campaignId: issue.id })
  assert.equal(c.status, 'paused')
  assert.equal(c.pauseReason, 'account_blocked')
  assert.equal(install.outbox(accountId).filter((r) => r.kind === 'campaign').length, 5)
  assert.equal((await expectError(() => owner.action('campaigns.resume', { campaignId: issue.id }))).code, 'account_blocked')
  await stores.applyPolicy(policy(1004, 'active', null))
  await owner.action('campaigns.resume', { campaignId: issue.id })
  assert.equal((await drive(install, owner, issue.id)).status, 'sent')
  assert.equal(install.outbox(accountId).filter((r) => r.kind === 'campaign').length, 12)
})
